"""Database connection and schema setup helpers."""

import psycopg2

from config import get_database_config


def connect():
    """Open and return a connection using the current environment settings."""
    return psycopg2.connect(**get_database_config())


def initialize_database():
    """Create the contacts table and its lookup indexes when needed."""
    with connect() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS contacts (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username TEXT NOT NULL,
                    phone TEXT NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    CONSTRAINT contacts_username_phone_unique UNIQUE (username, phone)
                )
                """
            )
            cursor.execute(
                "CREATE INDEX IF NOT EXISTS contacts_username_idx ON contacts (LOWER(username))"
            )
            cursor.execute(
                "CREATE INDEX IF NOT EXISTS contacts_phone_idx ON contacts (phone)"
            )
