"""Database connection and Practice 7 compatible schema setup."""

from pathlib import Path

import psycopg2

from config import get_database_config


def connect():
    return psycopg2.connect(**get_database_config())


def initialize_database():
    """Create the contacts table and install the Practice 8 SQL routines."""
    folder = Path(__file__).resolve().parent
    with connect() as connection, connection.cursor() as cursor:
        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS contacts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL,
                phone TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                CONSTRAINT contacts_username_phone_unique UNIQUE (username, phone)
            )
            """
        )
        cursor.execute(
            "CREATE INDEX IF NOT EXISTS contacts_username_idx ON contacts (LOWER(username))"
        )
        cursor.execute(
            "CREATE INDEX IF NOT EXISTS contacts_phone_idx ON contacts (phone)"
        )
        for script in ("functions.sql", "procedures.sql"):
            cursor.execute((folder / script).read_text(encoding="utf-8"))
